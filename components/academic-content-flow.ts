export function academicFlow(slug: string, kind: 'school' | 'program', recordId = ''): FlowStep[] {
  if(kind==='program' && slug==='mba-human-resource')return [
    {mode:'section',headings:['MBA in Human Resource Tracks']},
    {mode:'section',headings:['Salient Features']},
    {mode:'tabs',headings:['Program Structure','Eligibility Criteria','Fee Structure','Scholarship','Career Opportunities']},
    {mode:'section',headings:['Other Specialization']},
    {mode:'section',headings:['Placements + recruiters']},
    {mode:'section',headings:['International section']},
    {mode:'section',headings:['News']},
    {mode:'section',headings:['FAQs']},
  ];
  const fallback = kind === 'school'
    ? ['OUR PROGRAMS', 'Why choose', 'Placements + recruiters', 'Faculty', 'News', 'International section', 'FAQs']
    : ['Program specialization', 'Salient Features', 'Tabs: Advantage @DGU | Program Structure | Eligibility Criteria | Fee Structure | Scholarship', 'Career Opportunities', 'Other Specialization', 'Placements + recruiters', 'International section', 'News', 'FAQs'];
  return (pageFlows[slug + ':' + recordId] || pageFlows[slug] || fallback)
    .filter(line => !/^(navigation|banner|introduction|logos|ACCA recognition|footer)/i.test(line))
    .map(line => ({ mode: line.includes('Tabs:') ? 'tabs' : line.includes('Accordion:') ?
        /tab ke andar|ke andar/.test(line) ? 'nested' : 'accordion' : 'section',
      headings: line.replace(/^.*?(Tabs|Accordion):\s*/, '').split(/\s+—\s+/)[0].split('|').map(text => text.trim()),
      parent: /tab ke andar|ke andar/.test(line) ? (/Guidelines/i.test(line) ? 'Guidelines' : /Admission/i.test(line) ? 'Admission' : 'Course Structure') : undefined }));
}
