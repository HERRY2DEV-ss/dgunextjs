import { apiPlain } from './dgu-content-api';

/** Heading aliases affect placement only; the visible content always comes from the API. */
export function academicSectionKey(value: string): string {
  const title = apiPlain(value).toLowerCase().replace(/programme/g, 'program').replace(/specialisation/g, 'specialization').replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, ' ').trim();
  if (/^our programs$/.test(title)) return 'programs';
  if (/faculty|industry mentors/.test(title)) return /industry mentors/.test(title) ? 'mentors' : 'faculty';
  if (/^news/.test(title)) return 'news';
  if (/^faq|frequently asked/.test(title)) return 'faqs';
  if (/^(?:(?:program|course) )?overview$/.test(title)) return 'overview';
  if (/^choose any two specializations? build future ready technology careers$/.test(title)) return 'specialization-intro';
  if (/^choose any two specializations?$/.test(title)) return 'specialization-options';
  if (/^why choose global mba/.test(title)) return 'global-difference';
  if (/^(?:why choose|what makes|what sets|why .*school|research strengths)/.test(title)) return 'difference';
  if (/global learning|study abroad|international section|international opportunities|global immersion|student education immersion/.test(title)) return 'international';
  if (/options at a glance|program comparison|comparison chart/.test(title)) return 'options';
  if (/global (?:career )?pathway|sap and sas pathway/.test(title)) return /sap and sas/.test(title) ? 'sap-pathway' : 'global-pathway';
  if (/learn across borders|hands on international exposure|choice of universities/.test(title)) return 'across-borders';
  if (/fee structure|fees? and charges/.test(title)) return 'fees';
  if (/eligib/.test(title)) return 'eligibility';
  if (/scholarship/.test(title)) return 'scholarship';
  if (/advantage.*dgu|advantage.*dbs/.test(title)) return 'advantage';
  if (/^(course|program|curriculum).*structure|^curriculum$|^program curriculum$/.test(title)) return 'structure';
  if (/program specification/.test(title)) return 'specification';
  if (/humanities|first degree specialization/.test(title)) return 'humanities';
  if (/management specialization|first degree.*bba/.test(title)) return 'management';
  if (/law specialization|specializations? in law|second degree/.test(title)) return 'law';
  if (/suggest.*baskets/.test(title)) return 'baskets';
  if (/dual specialization|choose any two specialization/.test(title)) return 'dual-specializations';
  if (/most preferred combination/.test(title)) return 'preferred-combination';
  if (/career success|higher education/.test(title)) return 'higher-education';
  if (/career (opportunit|prospect|path|scope)|employment opportunit/.test(title)) return 'careers';
  if (/other specialization/.test(title)) return 'other-programs';
  if (/^program specialization/.test(title)) return 'specializations';
  if (/^industry aligned curriculum$/.test(title)) return 'industry-aligned-curriculum';
  if (/placements?|top recruiters/.test(title)) return 'placements';
  if (/laborator|infrastructure/.test(title)) return 'laboratories';
  if (/salient features|usps? of|usps? of the/.test(title)) return 'features';
  if (/six pillars/.test(title)) return 'pillars';
  if (/approval letters/.test(title)) return 'approval';
  if (/^vision$/.test(title)) return 'vision';
  if (/^mission$/.test(title)) return 'mission';
  if (/application process/.test(title)) return 'application-process';
  if (/^selection(?: process)?$/.test(title)) return 'selection';
  if (/^documents|documents required/.test(title)) return 'documents';
  if (/registration.*residency|date of registration|residency period/.test(title)) return 'registration-residency';
  if (/coursework.*duration|course work|minimum and maximum degree duration|tentative class timings/.test(title)) return 'coursework-duration';
  if (/fellowship.*appointment|^fellowship$/.test(title)) return 'fellowship-appointment';
  if (/duties.*attendance|working hours|^attendance$|general responsibilities/.test(title)) return 'duties-attendance';
  if (/review.*publications|review of progress|publication requirements|evaluation and feedback/.test(title)) return 'review-publications';
  if (/exit.*liability|discontinuation|withdrawal|financial liability|unfinished research/.test(title)) return 'exit-liability';
  if (/co designed/.test(title)) return 'co-designed';
  if (/co delivered/.test(title)) return 'co-delivered';
  if (/co certified/.test(title)) return 'co-certified';
  if (/benefits of industry collaboration|industry collaboration benefits/.test(title)) return 'industry-benefits';
  if (/industry collaboration|collaborative industries|powered by|curriculum and industry integration/.test(title)) return 'industry';
  if (/nism.*(integration|capital)|capital markets focus/.test(title)) return 'nism';
  if (/^sap program/.test(title)) return 'sap';
  if (/^sas program/.test(title)) return 'sas';
  if (/iim.*residential/.test(title)) return 'iim';
  if (/social internships?/.test(title)) return 'social-internships';
  if (/legal internships?/.test(title)) return 'legal-internships';
  if (/moot court/.test(title)) return 'moot-court';
  if (/legal aid/.test(title)) return 'legal-aid';
  if (/guest (sessions|lectures)/.test(title)) return 'guest-sessions';
  if (/trial (court |)advocacy/.test(title)) return 'trial-advocacy';
  if (/judicial coaching/.test(title)) return 'judicial-coaching';
  if (/wellness/.test(title)) return 'wellness';
  if (/signature events|^events$/.test(title)) return 'events';
  if (/center of excellence|research disciplines.*centres|research centres/.test(title)) return 'research-centres';
  if (/research.*outcomes|student outcomes|program outcomes/.test(title)) return 'outcomes';
  if (/video/.test(title)) return 'video';
  if (/level.*duration/.test(title)) return 'level-duration';
  if (/global (learning )?experience.*classroom|a learning experience.*classroom/.test(title)) return 'global-experience';
  if (/global mindset/.test(title)) return 'global-mindset';
  if (/where this mba/.test(title)) return 'global-careers';
  if (/why choose global mba/.test(title)) return 'global-difference';
  return title;
}
